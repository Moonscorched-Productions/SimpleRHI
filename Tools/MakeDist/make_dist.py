#!/usr/bin/env python3
"""Generates the generated half of dist/: the single-header SimpleRHI.h, srhic.cpp, the shader include and the
ImGui backend. Run from anywhere:  python Tools/MakeDist/make_dist.py

The hand-written half of dist/ (README.txt, skills/, example/) is left untouched.

SimpleRHI.h layout (stb style):
    <public API, C, include-guarded>
    #ifdef SRHI_IMPLEMENTATION           runtime: common layer + every backend enabled for the platform (C++17)
    #ifdef SRHI_COMPILER_IMPLEMENTATION  Slang shader compiler (C++17, needs the Slang SDK)

Each backend and the compiler normally live in their own translation unit with helpers in an anonymous
namespace. To share one translation unit they are moved into named namespaces (srhi_d3d11_impl, ...).
"""

import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "Source" / "SimpleRHI"
DIST = ROOT / "dist"

PROJECT_INCLUDES = re.compile(r'^\s*#\s*include\s*(<SimpleRHI\.h>|"srhi_internal\.h"|"srhi_package\.h")\s*$')
FILE_HEADER = re.compile(r"\A/\*\*\n \* @ Author:.*?\*/\n+", re.S)


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def strip(text: str) -> str:
    """Drops the per-file author banner, #pragma once and includes of other SimpleRHI files."""
    text = FILE_HEADER.sub("", text)
    lines = [l for l in text.split("\n") if not PROJECT_INCLUDES.match(l) and l.strip() != "#pragma once"]
    return "\n".join(lines).strip("\n") + "\n"


def name_anonymous_namespace(text: str, ns: str, what: str) -> str:
    """Turns the file's top-level anonymous namespace into `namespace ns` and pulls file-scope using
    declarations (ComPtr) inside it, so two files can declare the same helper names in one translation unit."""
    usings = re.findall(r"^using [\w:]+::ComPtr;\n", text, re.M)
    text = re.sub(r"^using [\w:]+::ComPtr;\n", "", text, flags=re.M)
    opened = "namespace " + ns + "\n{\n" + "".join("    " + u for u in usings)
    text, n = re.subn(r"^namespace\n\{\n", lambda m: opened, text, count=1, flags=re.M)
    if n != 1:
        raise SystemExit(f"{what}: expected one top-level anonymous namespace")
    return text


def backend(filename: str, ns: str, factory: str) -> str:
    """A backend: anonymous namespace + a global factory. The factory moves into the namespace too and a
    one-line trampoline keeps the global symbol."""
    text = name_anonymous_namespace(strip(read(SRC / filename)), ns, filename)
    text, n = re.subn(r"^\} // namespace\n", "", text, count=1, flags=re.M)
    if n != 1:
        raise SystemExit(f"{filename}: expected '}} // namespace' closing the anonymous namespace")
    signature = f"srhiDevice* {factory}(const srhiDeviceDesc& desc)\n"
    if text.count(signature) != 1:
        raise SystemExit(f"{filename}: factory {factory} not found")
    text = text.replace(signature, "srhiDevice* CreateDeviceImpl(const srhiDeviceDesc& desc)\n")
    text += f"}} // namespace {ns}\n\n"
    text += f"srhiDevice* {factory}(const srhiDeviceDesc& desc) {{ return {ns}::CreateDeviceImpl(desc); }}\n"
    return text


def compiler() -> str:
    """The compiler: anonymous namespace + extern "C" entry points, which may legally stay inside a namespace."""
    text = name_anonymous_namespace(strip(read(SRC / "srhi_compiler.cpp")), "srhi_compiler_impl", "srhi_compiler.cpp")
    text, n = re.subn(r"^\} // namespace\n", "", text, count=1, flags=re.M)
    if n != 1:
        raise SystemExit("srhi_compiler.cpp: expected '} // namespace'")
    return text + "} // namespace srhi_compiler_impl\n"


def banner(title: str) -> str:
    bar = "// " + "=" * 117
    return f"\n{bar}\n// {title}\n{bar}\n\n"


def single_header() -> str:
    api = read(ROOT / "Include" / "SimpleRHI.h")
    api = api.replace(
        " * Single public header. It declares both the runtime (link `SimpleRHI`) and the offline shader compiler\n"
        " * (link `SimpleRHICompiler`, which pulls in Slang). The runtime never depends on Slang.\n",
        " * Single-header distribution (generated by Tools/MakeDist/make_dist.py, do not edit). The API is plain C.\n"
        " * The implementation is C++17 and is emitted where one of these is defined before including this file:\n"
        " *\n"
        " *   #define SRHI_IMPLEMENTATION            // the runtime, in exactly one .cpp (one .mm on Apple platforms)\n"
        " *   #define SRHI_COMPILER_IMPLEMENTATION   // the Slang shader compiler (needs the Slang SDK), in one .cpp\n"
        " *\n"
        " * The runtime never depends on Slang. Backends compiled into SRHI_IMPLEMENTATION:\n"
        " *   - D3D11 on Windows (disable with SRHI_NO_D3D11). MSVC links d3d11, dxgi, d3dcompiler and dxguid\n"
        " *     automatically; other toolchains must link them.\n"
        " *   - Metal on Apple platforms (disable with SRHI_NO_METAL). The file must be Objective-C++ with ARC\n"
        " *     (-fobjc-arc) and link Metal, QuartzCore, Foundation (and AppKit on macOS).\n"
        " *   - WebGPU under Emscripten (emdawnwebgpu, needs -sASYNCIFY), or on desktop when SRHI_ENABLE_WEBGPU is\n"
        " *     defined (wgpu-native: <webgpu/webgpu.h> and <webgpu/wgpu.h> on the include path).\n",
    )
    if "SRHI_COMPILER_IMPLEMENTATION" not in api:
        raise SystemExit("Include/SimpleRHI.h: header comment changed, update make_dist.py")
    api = api.replace("#pragma once\n", "#ifndef SIMPLERHI_H\n#define SIMPLERHI_H\n", 1)
    api = api.replace("// Shader compiler (link SimpleRHICompiler)", "// Shader compiler (define SRHI_COMPILER_IMPLEMENTATION)")
    api = api.rstrip("\n") + "\n\n#endif // SIMPLERHI_H\n"

    package = strip(read(SRC / "srhi_package.h"))
    out = [api]

    out.append(banner("Shader package format (shared by the runtime and the compiler)"))
    out.append("#if (defined(SRHI_IMPLEMENTATION) || defined(SRHI_COMPILER_IMPLEMENTATION)) && !defined(SRHI_PACKAGE_INCLUDED)\n")
    out.append("#define SRHI_PACKAGE_INCLUDED\n\n")
    out.append("#ifndef __cplusplus\n#error \"The SimpleRHI implementation is C++17: define SRHI_IMPLEMENTATION in a .cpp (or .mm) file.\"\n#endif\n\n")
    out.append(package)
    out.append("\n#endif // SRHI_PACKAGE_INCLUDED\n")

    out.append(banner("Runtime implementation"))
    out.append("#if defined(SRHI_IMPLEMENTATION) && !defined(SRHI_IMPLEMENTATION_INCLUDED)\n")
    out.append("#define SRHI_IMPLEMENTATION_INCLUDED\n\n")
    out.append(
        "#if defined(_WIN32) && !defined(SRHI_NO_D3D11) && !defined(SRHI_HAS_D3D11)\n"
        "    #define SRHI_HAS_D3D11\n"
        "#endif\n"
        "#if defined(__APPLE__) && !defined(SRHI_NO_METAL) && !defined(SRHI_HAS_METAL)\n"
        "    #define SRHI_HAS_METAL\n"
        "#endif\n"
        "#if (defined(__EMSCRIPTEN__) || defined(SRHI_ENABLE_WEBGPU)) && !defined(SRHI_HAS_WEBGPU)\n"
        "    #define SRHI_HAS_WEBGPU\n"
        "#endif\n"
        "#if defined(SRHI_HAS_METAL) && !defined(__OBJC__)\n"
        "    #error \"The Metal backend is Objective-C++: define SRHI_IMPLEMENTATION in a .mm file compiled with -fobjc-arc.\"\n"
        "#endif\n"
        "#if !defined(SRHI_HAS_D3D11) && !defined(SRHI_HAS_METAL) && !defined(SRHI_HAS_WEBGPU)\n"
        "    #error \"No SimpleRHI backend for this platform: define SRHI_ENABLE_WEBGPU to use wgpu-native.\"\n"
        "#endif\n"
        "#if defined(SRHI_HAS_D3D11) && defined(_MSC_VER)\n"
        "    #pragma comment(lib, \"d3d11\")\n"
        "    #pragma comment(lib, \"dxgi\")\n"
        "    #pragma comment(lib, \"d3dcompiler\")\n"
        "    #pragma comment(lib, \"dxguid\")\n"
        "#endif\n"
    )
    out.append(banner("srhi_internal.h"))
    out.append(strip(read(SRC / "srhi_internal.h")))
    out.append(banner("srhi_common.cpp"))
    out.append(strip(read(SRC / "srhi_common.cpp")))
    for macro, filename, ns, factory in [
        ("SRHI_HAS_D3D11", "srhi_d3d11.cpp", "srhi_d3d11_impl", "srhiCreateDeviceD3D11"),
        ("SRHI_HAS_METAL", "srhi_metal.mm", "srhi_metal_impl", "srhiCreateDeviceMetal"),
        ("SRHI_HAS_WEBGPU", "srhi_webgpu.cpp", "srhi_webgpu_impl", "srhiCreateDeviceWebGPU"),
    ]:
        out.append(banner(filename))
        out.append(f"#ifdef {macro}\n\n")
        out.append(backend(filename, ns, factory))
        out.append(f"\n#endif // {macro}\n")
    out.append("\n#endif // SRHI_IMPLEMENTATION\n")

    out.append(banner("Shader compiler implementation (srhi_compiler.cpp)"))
    out.append("#if defined(SRHI_COMPILER_IMPLEMENTATION) && !defined(SRHI_COMPILER_IMPLEMENTATION_INCLUDED)\n")
    out.append("#define SRHI_COMPILER_IMPLEMENTATION_INCLUDED\n\n")
    out.append(compiler())
    out.append("\n#endif // SRHI_COMPILER_IMPLEMENTATION\n")
    return "".join(out)


def srhic() -> str:
    text = strip(read(ROOT / "Source" / "Tools" / "ShaderCompiler" / "main.cpp"))
    include = '#include "../../SimpleRHI/srhi_package.h"\n'
    if include not in text:
        raise SystemExit("srhic main.cpp: package include not found")
    text = text.replace(include, "")
    marker = "#include <cstdio>\n"
    head = (
        "// Single-file build: this file plus SimpleRHI.h and the Slang SDK.\n"
        "//   cl /std:c++17 /EHsc srhic.cpp /I <slang>/include <slang>/lib/slang.lib\n"
        "//   c++ -std=c++17 srhic.cpp -I <slang>/include -L <slang>/lib -lslang -o srhic\n"
        "\n"
        "#define SRHI_COMPILER_IMPLEMENTATION\n"
        '#include "SimpleRHI.h"\n\n'
    )
    return "// Generated by Tools/MakeDist/make_dist.py from Source/Tools/ShaderCompiler/main.cpp. Do not edit.\n\n" + text.replace(marker, head + marker, 1)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)} ({len(text.splitlines())} lines)")


def main() -> None:
    write(DIST / "SimpleRHI.h", single_header())
    write(DIST / "srhic.cpp", srhic())
    write(DIST / "SimpleRHI.slang", read(SRC / "Shaders" / "SimpleRHI.slang").replace(
        '(srhic adds Source/SimpleRHI/Shaders to the include path)', "(pass this file's directory to srhic with -I)"))
    for name in ["imgui_impl_srhi.h", "imgui_impl_srhi.cpp", "imgui_impl_srhi_shader.h"]:
        text = read(ROOT / "Source" / "ImGui" / name).replace("#include <SimpleRHI.h>", '#include "SimpleRHI.h"')
        write(DIST / "imgui" / name, text)


if __name__ == "__main__":
    main()
